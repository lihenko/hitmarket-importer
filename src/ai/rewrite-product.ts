function createParamsSchema(
  paramsCount: number
) {

  const properties: Record<string, unknown> = {};

  const required: string[] = [];


  for (
    let i = 0;
    i < paramsCount;
    i++
  ) {

    const key =
      `p${i + 1}`;


    properties[key] = {

      type:
        "object",

      properties: {

        name: {
          type:
            "string",
        },

        value: {
          type:
            "string",
        },

        unit: {

          anyOf: [

            {
              type:
                "string",
            },

            {
              type:
                "null",
            },

          ],

        },

      },

      required: [
        "name",
        "value",
        "unit",
      ],

      additionalProperties:
        false,
    };


    required.push(key);
  }


  return {

    type:
      "object",

    properties,

    required,

    additionalProperties:
      false,

  };
}


